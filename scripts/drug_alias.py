def _normalize(text):
    return (text or "").strip()


def expand_aliases(name):
    """
    薬剤名または分類名を受け取り、対応しうる一般名の集合を返す
    （分類名ならALIAS_MAPの値を、一般名ならそれ自身を含む）。
    """
    name = _normalize(name)
    result = {name}
    if name in ALIAS_MAP:
        result.update(ALIAS_MAP[name])
    # 逆引き：一般名からその一般名を含む分類名も拾う
    for category, members in ALIAS_MAP.items():
        if name in members:
            result.add(category)
    return result


def interaction_text_mentions(interaction_text, target_generic_name, target_brand_name=None):
    """
    ある薬の相互作用テキスト（drug_name_or_class列）が、
    target_generic_name（または target_brand_name）に該当する薬剤・分類を
    言及しているかどうかを判定する。
    """
    text = _normalize(interaction_text)
    if not text:
        return False

    candidates = set()
    candidates |= expand_aliases(target_generic_name)
    if target_brand_name:
        candidates |= expand_aliases(target_brand_name)

    for candidate in candidates:
        if candidate and candidate in text:
            return True
    return False
